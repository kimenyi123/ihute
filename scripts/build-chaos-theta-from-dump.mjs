/**
 * Builds sql/chaos_theta.sql from all chaos_beta_*.sql table dumps in Dump20260406.
 * Skips chaos_beta_routines.sql (procedures/views — append separately if needed).
 * Run: node scripts/build-chaos-theta-from-dump.mjs
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, "..")

const DUMP_DIR = "C:/Users/kimai/OneDrive/Documents/dumps/Dump20260406"
const outPath = path.join(ROOT, "sql", "chaos_theta.sql")
const addonPath = path.join(ROOT, "sql", "chaos_theta_grandma_addon.sql")

function extractTableStatements(fileContent) {
  const blocks = []
  let pos = 0
  while (pos < fileContent.length) {
    const createIdx = fileContent.indexOf("CREATE TABLE `", pos)
    if (createIdx === -1) break
    let start = fileContent.lastIndexOf("DROP TABLE IF EXISTS `", createIdx)
    if (start === -1 || createIdx - start > 2000) {
      start = createIdx
    }
    const engineIdx = fileContent.indexOf("ENGINE=", createIdx)
    if (engineIdx === -1) {
      pos = createIdx + 1
      continue
    }
    const endSemi = fileContent.indexOf(";", engineIdx)
    if (endSemi === -1) break
    const stmt = fileContent.slice(start, endSemi + 1).trim()
    if (stmt.includes("CREATE TABLE `")) {
      blocks.push(stmt)
    }
    pos = endSemi + 1
  }
  return blocks
}

const header = `-- =============================================================================
-- chaos_theta — FULL replica of chaos_beta table structures (from Dump20260406)
-- + Grandma extensions (grandma_* tables + account_buyer/seller/rider)
--
-- Generated by scripts/build-chaos-theta-from-dump.mjs — re-run after new dumps.
-- Review DEFINER and routines separately (chaos_beta_routines.sql not inlined).
-- =============================================================================

CREATE DATABASE IF NOT EXISTS \`chaos_theta\`
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;

USE \`chaos_theta\`;

SET FOREIGN_KEY_CHECKS=0;
SET UNIQUE_CHECKS=0;

`

const footer = `
SET FOREIGN_KEY_CHECKS=1;
SET UNIQUE_CHECKS=1;

-- =============================================================================
-- PART 2 — Grandma-specific & split-account tables (theta additions)
-- IHUTE code can target chaos_theta with same table names as chaos_beta;
-- these extra tables support FMCG slice, stock ledger, optional ratings.
-- =============================================================================

`

function readGrandmaAddon() {
  if (fs.existsSync(addonPath)) {
    return fs.readFileSync(addonPath, "utf8")
  }
  return ""
}

function main() {
  const files = fs
    .readdirSync(DUMP_DIR)
    .filter((f) => f.startsWith("chaos_beta_") && f.endsWith(".sql"))
    .filter((f) => f !== "chaos_beta_routines.sql")
    .sort((a, b) => a.localeCompare(b))

  const parts = [header]

  for (const f of files) {
    const full = path.join(DUMP_DIR, f)
    const content = fs.readFileSync(full, "utf8")
    const blocks = extractTableStatements(content)
    for (const b of blocks) {
      parts.push(b)
      parts.push("\n\n")
    }
    if (blocks.length === 0 && content.includes("CREATE TABLE")) {
      console.warn("No block extracted from", f)
    }
  }

  parts.push(footer)
  const addon = readGrandmaAddon()
  if (addon) {
    parts.push(addon)
  }

  fs.writeFileSync(outPath, parts.join(""), "utf8")
  console.log("Wrote", outPath, "files:", files.length, "approx size", fs.statSync(outPath).size)
}

main()
