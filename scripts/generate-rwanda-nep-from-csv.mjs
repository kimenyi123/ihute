/**
 * Reads NEP villages CSV (Province, District, Sector, Cellule, Village).
 * Writes:
 *   - lib/rwanda-nep-hierarchy.ts — sectors per district (CSV order), cellules, villages
 *   - lib/rwanda-district-cells.ts — thin re-export for legacy imports
 *
 * Usage: node scripts/generate-rwanda-nep-from-csv.mjs [path-to-csv]
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, "..")

function parseCSVLine(line) {
  const out = []
  let cur = ""
  let q = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (q) {
      if (c === '"') {
        if (line[i + 1] === '"') {
          cur += '"'
          i++
        } else {
          q = false
        }
      } else {
        cur += c
      }
    } else {
      if (c === '"') q = true
      else if (c === ",") {
        out.push(cur)
        cur = ""
      } else cur += c
    }
  }
  out.push(cur)
  return out
}

function norm(s) {
  if (!s) return ""
  s = s.trim()
  if (s.length > 1 && s === s.toUpperCase() && /[A-Za-z]/.test(s)) {
    return s.charAt(0) + s.slice(1).toLowerCase()
  }
  return s
}

function keyDS(d, s) {
  return JSON.stringify([d, s])
}

function keyDSC(d, s, c) {
  return JSON.stringify([d, s, c])
}

const csvPath =
  process.argv[2] ||
  path.join(root, "data", "FINAL_LIST_OF_REVISED_NEP_VILLAGES_JULY_2023-PUBLISHED.csv")

if (!fs.existsSync(csvPath)) {
  console.error("CSV not found:", csvPath)
  process.exit(1)
}

const text = fs.readFileSync(csvPath, "utf8")
const lines = text.split(/\r?\n/).filter((l) => l.trim())

/** district -> ordered unique sectors (CSV row order) */
const districtSectors = new Map()
const sectorSeenByDistrict = new Map()

/** key JSON [d,s] -> ordered unique cellules */
const sectorCellules = new Map()
const celluleSeen = new Map()

/** key JSON [d,s,c] -> ordered unique villages */
const celluleVillages = new Map()
const villageSeen = new Map()

function addOrdered(map, seenMap, key, raw) {
  const v = norm(raw)
  if (!v) return
  const lk = v.toLowerCase()
  if (!seenMap.has(key)) seenMap.set(key, new Set())
  const seen = seenMap.get(key)
  if (seen.has(lk)) return
  seen.add(lk)
  if (!map.has(key)) map.set(key, [])
  map.get(key).push(v)
}

for (let i = 1; i < lines.length; i++) {
  const cols = parseCSVLine(lines[i])
  if (cols.length < 6) continue
  const district = norm(cols[2])
  const sector = norm(cols[3])
  const cellule = norm(cols[4])
  const village = norm(cols[5])
  if (!district || !sector) continue

  addOrdered(districtSectors, sectorSeenByDistrict, district, cols[3]?.trim() || sector)

  const ds = keyDS(district, sector)
  if (cellule) addOrdered(sectorCellules, celluleSeen, ds, cols[4]?.trim() || cellule)

  if (cellule && village) {
    const dsc = keyDSC(district, sector, cellule)
    addOrdered(celluleVillages, villageSeen, dsc, cols[5]?.trim() || village)
  }
}

const sortedDistricts = [...districtSectors.keys()].sort((a, b) =>
  a.localeCompare(b, "en", { sensitivity: "base" })
)

const hierarchyBody = []
hierarchyBody.push("/**")
hierarchyBody.push(" * NEP July 2023 — Province → District → Sector → Cellule → Village.")
hierarchyBody.push(" * Lists follow CSV row order (first occurrence) for dropdowns.")
hierarchyBody.push(" * Generated by scripts/generate-rwanda-nep-from-csv.mjs.")
hierarchyBody.push(" */")
hierarchyBody.push("")
hierarchyBody.push(`export const DISTRICT_CELLS: Record<string, string[]> = {`)
for (const d of sortedDistricts) {
  const arr = districtSectors.get(d) || []
  hierarchyBody.push(`  ${JSON.stringify(d)}: ${JSON.stringify(arr)},`)
}
hierarchyBody.push("}")
hierarchyBody.push("")
hierarchyBody.push("/** Sector + Cellule → villages (key = JSON.stringify([district, sector, cellule])) */")
hierarchyBody.push("export const CELLULE_VILLAGES: Record<string, string[]> = {")

const sortedSCKeys = [...celluleVillages.keys()].sort()
for (const k of sortedSCKeys) {
  const arr = celluleVillages.get(k) || []
  hierarchyBody.push(`  ${JSON.stringify(k)}: ${JSON.stringify(arr)},`)
}
hierarchyBody.push("}")
hierarchyBody.push("")
hierarchyBody.push("/** District + Sector → cellules (key = JSON.stringify([district, sector])) */")
hierarchyBody.push("export const SECTOR_CELLULES: Record<string, string[]> = {")

const sortedDSKeys = [...sectorCellules.keys()].sort()
for (const k of sortedDSKeys) {
  const arr = sectorCellules.get(k) || []
  hierarchyBody.push(`  ${JSON.stringify(k)}: ${JSON.stringify(arr)},`)
}
hierarchyBody.push("}")
hierarchyBody.push("")
hierarchyBody.push("export function cellsForDistrict(district: string): string[] {")
hierarchyBody.push("  if (!district) return []")
hierarchyBody.push("  return DISTRICT_CELLS[district] ?? []")
hierarchyBody.push("}")
hierarchyBody.push("")
hierarchyBody.push(
  "/** Geographic Sector (NEP) — same as legacy `cellsForDistrict` name in older code. */"
)
hierarchyBody.push("export function sectorsForDistrict(district: string): string[] {")
hierarchyBody.push("  return cellsForDistrict(district)")
hierarchyBody.push("}")
hierarchyBody.push("")
hierarchyBody.push("export function cellulesForDistrictSector(district: string, sector: string): string[] {")
hierarchyBody.push("  if (!district || !sector) return []")
hierarchyBody.push("  return SECTOR_CELLULES[JSON.stringify([district, sector])] ?? []")
hierarchyBody.push("}")
hierarchyBody.push("")
hierarchyBody.push(
  "export function villagesForDistrictSectorCellule(district: string, sector: string, cellule: string): string[] {"
)
hierarchyBody.push("  if (!district || !sector || !cellule) return []")
hierarchyBody.push("  return CELLULE_VILLAGES[JSON.stringify([district, sector, cellule])] ?? []")
hierarchyBody.push("}")
hierarchyBody.push("")

const hierarchyPath = path.join(root, "lib", "rwanda-nep-hierarchy.ts")
fs.writeFileSync(hierarchyPath, hierarchyBody.join("\n"), "utf8")
console.log("Wrote", hierarchyPath)

const shim = `/** Re-export — see rwanda-nep-hierarchy for cellule/village helpers. */
export {
  DISTRICT_CELLS,
  cellsForDistrict,
} from "./rwanda-nep-hierarchy"
`
const shimPath = path.join(root, "lib", "rwanda-district-cells.ts")
fs.writeFileSync(shimPath, shim, "utf8")
console.log("Wrote", shimPath, "districts:", sortedDistricts.length)
